"""Dataset provenance helpers (torch-free).

CHEM can be trained on real data or on the tiny synthetic demo set produced by
``data/create_synthetic_demo.py``.  The synthetic set is trivially separable, so
a checkpoint trained on it must never be presented as a genuinely trained model.

The synthetic generator drops a marker file into its output directory; the
training pipeline looks for that marker and records the result in the
checkpoint metadata.  Keeping this in a torch-free module lets the data scripts
use it without importing the deep-learning stack.
"""

from __future__ import annotations

import os
from typing import Optional

# Name of the marker file written next to the synthetic jsonl splits.
SYNTHETIC_MARKER_FILENAME = "SYNTHETIC_DATA.txt"

_MARKER_TEXT = (
    "This directory contains SYNTHETIC demo data generated by "
    "data/create_synthetic_demo.py.\n"
    "It exists only to smoke-test the CHEM pipeline. Models trained on it must "
    "not be reported as trained moderation models.\n"
)


def write_synthetic_marker(directory: str) -> str:
    """Write the synthetic-data marker file into ``directory``.

    Parameters
    ----------
    directory : str
        Output directory of the synthetic dataset (must already exist).

    Returns
    -------
    str
        Path of the marker file.
    """
    path = os.path.join(directory, SYNTHETIC_MARKER_FILENAME)
    with open(path, "w", encoding="utf-8") as handle:
        handle.write(_MARKER_TEXT)
    return path


def is_synthetic_dir(directory: Optional[str]) -> bool:
    """Return True if ``directory`` carries the synthetic-data marker.

    Parameters
    ----------
    directory : str or None
        Dataset root directory (``None`` is treated as "not synthetic").

    Returns
    -------
    bool
        Whether the marker file exists in ``directory``.
    """
    if not directory:
        return False
    return os.path.isfile(
        os.path.join(os.path.expanduser(directory), SYNTHETIC_MARKER_FILENAME)
    )
